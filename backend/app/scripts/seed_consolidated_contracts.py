def parse_date(date_str):
    if not date_str:
        return None
    try:
        return datetime.strptime(date_str, "%Y-%m-%d").date()
    except Exception:
        return None

def seed_contracts():
    db = SessionLocal()
    try:
        print(f"Iniciando ingesta de {len(CONTRACTS_DATA)} contratos consolidados...")
        created_contracts = 0
        updated_contracts = 0
        created_contractors = 0

        for c_data in CONTRACTS_DATA:
            doc_raw = c_data["documento"]
            nombre = c_data["titular"].strip()
            
            # Buscar o crear contratista
            contractor = db.query(Contratista).filter(
                (Contratista.numero_documento == doc_raw) | 
                (Contratista.nombre_o_razon_social == nombre)
            ).first()

            is_juridica = any(kw in nombre.upper() for kw in ["SAS", "S.A.S.", "ASOCIACION", "PARROQUIA", "BOMBEROS", "SISTEMAS", "LABORATORIOS", "COMPANY", "ESTACIONES", "STRAPARTES"]) or doc_raw.startswith("8") or doc_raw.startswith("9")

            if not contractor:
                contractor = Contratista(
                    tipo_persona=TipoPersona.JURIDICA if is_juridica else TipoPersona.NATURAL,
                    tipo_documento=TipoDocumento.NIT if is_juridica else TipoDocumento.CC,
                    numero_documento=doc_raw,
                    nombre_o_razon_social=nombre,
                    municipio="Yolombó",
                    departamento="Antioquia",
                    regimen_tributario=RegimenTributario.RESPONSABLE_IVA if is_juridica else RegimenTributario.NO_RESPONSABLE_IVA
                )
                db.add(contractor)
                db.flush()
                created_contractors += 1
                print(f"+ Contratista creado: {nombre} ({doc_raw})")

            # Buscar o crear contrato
            contract = db.query(Contrato).filter(Contrato.numero_contrato == c_data["numero_contrato"]).first()
            val_letras = numero_a_letras_cop(c_data["valor_total"])
            
            tipologia_val = TipologiaContrato[c_data["tipologia"]]

            if not contract:
                contract = Contrato(
                    numero_contrato=c_data["numero_contrato"],
                    vigencia=2026,
                    modalidad_seleccion=ModalidadSeleccion.CONTRATACION_DIRECTA,
                    tipologia=tipologia_val,
                    contratista_id=contractor.id,
                    objeto=c_data["objeto"],
                    valor_inicial=c_data["valor_inicial"],
                    adicion_1=c_data["adicion_1"],
                    valor_total=c_data["valor_total"],
                    valor_en_letras=val_letras,
                    plazo_texto=c_data["plazo_texto"],
                    plazo_ejecucion=c_data["plazo_ejecucion"],
                    unidad_plazo=UnidadPlazo[c_data["unidad_plazo"]],
                    prorroga_1=c_data["prorroga_1"],
                    fecha_suscripcion=parse_date(c_data["fecha_suscripcion"]),
                    fecha_acta_inicio=parse_date(c_data["fecha_inicio"]),
                    fecha_terminacion=parse_date(c_data["fecha_terminacion"]),
                    supervisor_nombre=c_data["supervisor"],
                    supervisor_cargo="Gerente General",
                    cdp_numero=c_data["cdp"],
                    cdp_rubro=c_data["rubro"],
                    rp_numero=c_data["crp"],
                    estado=EstadoContrato.EN_EJECUCION
                )
                db.add(contract)
                created_contracts += 1
            else:
                contract.tipologia = tipologia_val
                contract.contratista_id = contractor.id
                contract.objeto = c_data["objeto"]
                contract.valor_inicial = c_data["valor_inicial"]
                contract.adicion_1 = c_data["adicion_1"]
                contract.valor_total = c_data["valor_total"]
                contract.valor_en_letras = val_letras
                contract.plazo_texto = c_data["plazo_texto"]
                contract.plazo_ejecucion = c_data["plazo_ejecucion"]
                contract.unidad_plazo = UnidadPlazo[c_data["unidad_plazo"]]
                contract.prorroga_1 = c_data["prorroga_1"]
                contract.fecha_suscripcion = parse_date(c_data["fecha_suscripcion"])
                contract.fecha_acta_inicio = parse_date(c_data["fecha_inicio"])
                contract.fecha_terminacion = parse_date(c_data["fecha_terminacion"])
                contract.supervisor_nombre = c_data["supervisor"]
                contract.cdp_numero = c_data["cdp"]
                contract.cdp_rubro = c_data["rubro"]
                contract.rp_numero = c_data["crp"]
                contract.estado = EstadoContrato.EN_EJECUCION
                updated_contracts += 1

        db.commit()
        print("\n" + "=" * 60)
        print("RESULTADO DE LA INGESTA:")
        print(f"Total contratos procesados: {len(CONTRACTS_DATA)}")
        print(f"Contratos nuevos creados: {created_contracts}")
        print(f"Contratos actualizados: {updated_contracts}")
        print(f"Contratistas nuevos registrados: {created_contractors}")
        print("=" * 60)

    except Exception as e:
        db.rollback()
        print(f"ERROR durante la ingesta: {e}")
        raise
    finally:
        db.close()

if __name__ == "__main__":
    seed_contracts()
